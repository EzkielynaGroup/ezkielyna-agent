export const uxLang = (): "en" | "id" =>
  (process.env.EZK_LANG || process.env.LC_ALL || process.env.LANG || "").toLowerCase().startsWith("id") ? "id" : "en"

export function ut(key: UxKey, vars: Record<string, string | number> = {}, lang = uxLang()) {
  const text = (lang === "id" ? id : en)[key]
  return text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""))
}

export const UX_STRINGS = { en, id }
